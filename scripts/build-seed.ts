// Turns the TypeScript seed content in db/seed/ into db/generated/seed.sql for D1.
// Run with: npm run seed:build
import { writeFileSync } from 'node:fs';
import * as seed from '../db/seed/index.ts';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return `'${String(v).replaceAll("'", "''")}'`;
};
const j = (v: unknown) => (v === undefined || v === null ? 'NULL' : q(JSON.stringify(v)));
const insert = (table: string, cols: string[], rows: unknown[][]) =>
  rows.map((r) => `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${r.join(', ')});`).join('\n');

const ids = new Set<string>();
for (const r of seed.requirements) {
  if (ids.has(r.id)) throw new Error(`Duplicate requirement id: ${r.id}`);
  ids.add(r.id);
}

const sql = [
  '-- GENERATED by scripts/build-seed.ts — edit db/seed/*.ts instead.',
  insert(
    'countries',
    ['code', 'name', 'flag', 'rabies_status', 'authority_name', 'authority_url', 'import_summary', 'quarantine_note', 'accepted_modes', 'pet_airports'],
    seed.countries.map((c) => [q(c.code), q(c.name), q(c.flag), q(c.rabiesStatus), q(c.authorityName), q(c.authorityUrl), q(c.importSummary), q(c.quarantineNote), j(c.acceptedModes), q(c.petAirports)]),
  ),
  insert(
    'country_groups',
    ['dest_code', 'origin_code', 'group_name', 'label'],
    seed.countryGroups.map((g) => [q(g.destCode), q(g.originCode), q(g.group), q(g.label)]),
  ),
  insert(
    'requirements',
    ['id', 'country_code', 'direction', 'species', 'applies_if', 'deadline_days', 'window_days', 'duration_days', 'depends_on', 'gap_days', 'critical', 'title', 'what', 'why', 'how', 'tip', 'est_cost', 'official_url', 'verification', 'last_checked', 'sort_order'],
    seed.requirements.map((r) => [q(r.id), q(r.countryCode), q(r.direction), q(r.species), j(r.appliesIf), q(r.deadlineDays), q(r.windowDays), q(r.durationDays), j(r.dependsOn), q(r.gapDays), q(r.critical), q(r.title), q(r.what), q(r.why), q(r.how), q(r.tip), q(r.estCost), q(r.officialUrl), q(r.verification), q(r.lastChecked), q(r.sortOrder)]),
  ),
  insert(
    'airlines',
    ['code', 'name', 'policy_url', 'modes', 'serves', 'hub', 'snub_nosed', 'summary', 'cabin_note', 'cargo_note', 'heat_note', 'crate_note', 'booking_tip', 'verification', 'last_checked'],
    seed.airlines.map((a) => [q(a.code), q(a.name), q(a.policyUrl), j(a.modes), j(a.serves), q(a.hub), q(a.snubNosed), q(a.summary), q(a.cabinNote), q(a.cargoNote), q(a.heatNote), q(a.crateNote), q(a.bookingTip), q(a.verification), q(a.lastChecked)]),
  ),
  insert(
    'airline_routes',
    ['airline_code', 'origin_code', 'dest_code', 'routing', 'note', 'rank'],
    seed.airlineRoutes.map((r) => [q(r.airlineCode), q(r.originCode), q(r.destCode), q(r.routing), q(r.note), q(r.rank)]),
  ),
  insert(
    'glossary',
    ['term', 'aliases', 'explanation'],
    seed.glossary.map((g) => [q(g.term), j(g.aliases), q(g.explanation)]),
  ),
].join('\n\n');

writeFileSync(new URL('../db/generated/seed.sql', import.meta.url), sql + '\n');
console.log(`Wrote seed.sql: ${seed.countries.length} countries, ${seed.requirements.length} requirements, ${seed.airlines.length} airlines, ${seed.glossary.length} glossary terms`);
